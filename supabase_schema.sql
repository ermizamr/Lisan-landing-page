CREATE TABLE IF NOT EXISTS public.community_validations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tuple_id TEXT NOT NULL,
    domain TEXT NOT NULL,
    scenario TEXT,
    grammar_element TEXT,
    target_lang TEXT NOT NULL,        -- 'amh', 'orm', 'tir', 'som'
    english_text TEXT NOT NULL,
    original_target TEXT,
    validated_text TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'approved', -- 'approved', 'edited', 'rejected'
    reviewer_note TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL
);

-- Index frequently queried columns for high-speed dashboard analytics
CREATE INDEX IF NOT EXISTS idx_community_validations_lang ON public.community_validations (target_lang);
CREATE INDEX IF NOT EXISTS idx_community_validations_domain ON public.community_validations (domain);
CREATE INDEX IF NOT EXISTS idx_community_validations_tuple ON public.community_validations (tuple_id);
CREATE INDEX IF NOT EXISTS idx_community_validations_status ON public.community_validations (status);

-- Enable Row Level Security (RLS)
ALTER TABLE public.community_validations ENABLE ROW LEVEL SECURITY;

-- Allow anonymous community reviewers to submit validation entries
CREATE POLICY "Allow public inserts" ON public.community_validations
    FOR INSERT
    WITH CHECK (true);

-- Allow public read access to community validations (for progress counters and exports)
CREATE POLICY "Allow public reads" ON public.community_validations
    FOR SELECT
    USING (true);

-- Optional: View to aggregate approval rates per language
CREATE OR REPLACE VIEW public.validation_stats AS
SELECT 
    target_lang,
    domain,
    status,
    COUNT(*) AS total_reviews,
    MIN(created_at) AS first_review,
    MAX(created_at) AS last_review
FROM public.community_validations
GROUP BY target_lang, domain, status;
